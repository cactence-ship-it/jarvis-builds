#!/usr/bin/env python3
"""Generate docs/VERI_SOZLUGU.md - the data dictionary of every spec parameter (Turkish).

    python tools/data_dictionary.py          write it
    python tools/data_dictionary.py --check  fail if it is stale

Generated from specs/kartal_s_1997.yaml and EVIDENCE_REGISTER.md only; the data class column
(USER_CONFIRMED, DOCUMENT_CONFIRMED, MEASURED, SOURCE_SUPPORTED, ESTIMATED, UNKNOWN) is derived
by kartal_twin.spec.data_class (D-026), never typed by hand.
"""
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from kartal_twin import PROJECT_ROOT  # noqa: E402
from kartal_twin.spec import DATA_CLASSES, data_class, iter_parameters, load_evidence, load_spec  # noqa: E402

OUT = PROJECT_ROOT / "docs" / "VERI_SOZLUGU.md"
MEANING = {
    "MEASURED": "Araç üzerinde fiziksel ölçümle elde edildi (MEASUREMENT kanıtı, VERIFIED).",
    "DOCUMENT_CONFIRMED": "Ruhsat veya teknik belgeyle doğrulandı (DOCUMENT/PHOTO kanıtı, VERIFIED).",
    "USER_CONFIRMED": "Araç sahibi doğrudan söyledi (USER_STATEMENT, güven HIGH); belge veya ölçü olmadan ESTIMATED kalır.",
    "SOURCE_SUPPORTED": "Teknik kaynakla destekleniyor (LITERATURE, güven MEDIUM/HIGH).",
    "ESTIMATED": "Geçici mühendislik varsayımı veya zayıf kaynak (ASSUMPTION ya da güven LOW).",
    "UNKNOWN": "Henüz bilinmiyor; değer yok.",
}


def _cell(v) -> str:
    return "" if v is None else str(v).replace("|", "/").replace("\n", " ")


def render() -> str:
    spec, ev = load_spec(), load_evidence()
    rows, counts = [], Counter()
    for pid, p in iter_parameters(spec):
        dc = data_class(p, ev)
        counts[dc] += 1
        val = "-" if p["value"] is None else f"{p['value']}" + (f" {p['unit']}" if p["unit"] else "")
        tol = "" if p["tolerance"] is None else f"± {p['tolerance']}"
        rows.append(f"| `{pid}` | {_cell(p['name'])} | {_cell(val)} | {tol} | {dc} | {p['status']} / {p['confidence']} "
                    f"| {', '.join(p['source']) or '-'} | {_cell(p['verify_by'])} |")
    lines = ["# Veri Sözlüğü - Kartal S (VEH-01)", "",
             "<!-- GENERATED by `python tools/data_dictionary.py`. Elle düzenlemeyin. -->", "",
             f"Spec revizyonu {spec['revision']}: {sum(counts.values())} parametre. Değerler ve açıklamalar "
             "`specs/kartal_s_1997.yaml` içindedir; bu tablo yalnızca özetidir.", "",
             "## Veri sınıfları (D-026)", "", "| Sınıf | Anlamı | Adet |", "|---|---|---|"]
    lines += [f"| {c} | {MEANING[c]} | {counts[c]} |" for c in DATA_CLASSES]
    lines += ["", "Sınıf, durum (VERIFIED/ESTIMATED/UNKNOWN), güven ve kanıt türünden otomatik türetilir. "
              "ESTIMATED değerler kesin ölçü değildir; gerekçeleri ve nasıl doğrulanacakları spec'teki "
              "`notes` ve `verify_by` alanlarındadır.", "",
              "## Parametreler", "",
              "| Parametre | Ad | Değer | Tolerans | Sınıf | Durum / güven | Kaynak | Nasıl doğrulanır |",
              "|---|---|---|---|---|---|---|---|"] + rows + [""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("data dictionary up to date" if ok else "docs/VERI_SOZLUGU.md is stale - run tools/data_dictionary.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
